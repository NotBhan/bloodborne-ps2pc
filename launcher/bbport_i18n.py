def system_language():
    """Detects system language from environment; defaults to 'en'."""
    for key in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        value = os.environ.get(key, "")
        if value:
            low = value.lower()
            if low.startswith("fr"):
                return "fr"
            if low.startswith("ru"):
                return "ru"
            if low.startswith("zh"):
                return "zh"
            if low.startswith("ko"):
                return "ko"
            if low.startswith("ja"):
                return "ja"
            return "en"
    return "en"


_language = "en"


def set_language(choice):
    """choice: 'en', 'fr', 'ru', 'zh', 'ko', 'ja' or ''/None for system."""
    global _language
    if choice in ("en", "fr", "ru", "zh", "ko", "ja"):
        _language = choice
    elif not choice:
        _language = system_language()
    else:
        _language = "en"


def language():
    return _language


def current_language():
    return _language


def translate(text, lang=None):
    if lang is None:
        return tr(text)
    old = _language
    try:
        set_language(lang)
        return tr(text)
    finally:
        set_language(old)


def tr(text):
    """Translates `text` into the current language, falling back to English."""
    if not text or not isinstance(text, str):
        return text

    # Canonical English resolution: distinguish legacy Cyrillic Russian keys
    is_ru_src = text in EN and any("\u0400" <= c <= "\u04FF" for c in text)
    en_text = EN[text] if is_ru_src else EN.get(text, text)

    if _language == "en":
        return en_text

    if _language == "ru":
        if is_ru_src:
            return text
        return RU.get(en_text, en_text)

    catalog = CATALOGS.get(_language)
    if catalog and en_text in catalog:
        return catalog[en_text]

    # Predictable fallback to English, never arbitrary language
    return en_text
